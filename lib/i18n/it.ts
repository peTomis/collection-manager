const ERROR_PATTERNS: [RegExp, (...groups: string[]) => string][] = [
  [/^Download failed \((\d+)\)\. Keep the app online and try again\.$/, (status) => `Download non riuscito (${status}). Resta online e riprova.`],
  [/^Download failed \((\d+)\)\. Reload and try again\.$/, (status) => `Download non riuscito (${status}). Ricarica e riprova.`],
  [/^Too many downloads\. Try again in (\d+) minutes\.$/, (minutes) => `Troppi download. Riprova tra ${minutes} minuti.`],
  [/^Too many offline downloads\. Try again in (\d+) minutes\.$/, (minutes) => `Troppi download offline. Riprova tra ${minutes} minuti.`],
];

const translateError = (message: string) => {
  if (ERRORS[message]) return ERRORS[message];
  for (const [pattern, text] of ERROR_PATTERNS) {
    const match = message.match(pattern);
    if (match) return text(...match.slice(1));
  }
  return message;
};

